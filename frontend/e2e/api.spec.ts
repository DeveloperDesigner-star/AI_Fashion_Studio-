import { readFileSync } from 'node:fs'
import { expect, test } from '@playwright/test'
import { bearer, registerMember, uniqueEmail } from './helpers'

const PORTRAIT = readFileSync('e2e/fixtures/portrait.png')

test.describe('API security and honesty checks', () => {
  test('private media is owner-only and unauthenticated access is rejected', async ({ request }) => {
    const owner = await registerMember(request, 'media-owner')
    const upload = await request.post('/api/v1/media/upload', {
      headers: bearer(owner.accessToken),
      multipart: {
        file: { name: 'portrait.png', mimeType: 'image/png', buffer: PORTRAIT },
        kind: 'photo',
        view: 'front',
      },
    })
    expect(upload.status(), await upload.text()).toBe(201)
    const asset = (await upload.json()) as { id: string; kind: string; mime_type: string }
    expect(asset.kind).toBe('photo')
    expect(asset.mime_type).toMatch(/^image\//)

    const ownerRead = await request.get(`/api/v1/media/${asset.id}/content`, {
      headers: bearer(owner.accessToken),
    })
    expect(ownerRead.status()).toBe(200)
    expect(ownerRead.headers()['content-type']).toContain('image/')

    expect((await request.get(`/api/v1/media/${asset.id}/content`)).status()).toBe(401)

    const strangerEmail = uniqueEmail('media-stranger')
    const stranger = await request.post('/api/v1/auth/register', {
      data: {
        email: strangerEmail,
        password: 'AuditPass123',
        full_name: 'Media Stranger',
        accept_terms: true,
      },
    })
    expect(stranger.status()).toBe(201)
    const strangerBody = (await stranger.json()) as { access_token: string }
    expect(
      (
        await request.get(`/api/v1/media/${asset.id}/content`, {
          headers: bearer(strangerBody.access_token),
        })
      ).status(),
    ).toBe(404)

    expect(
      (await request.get('/api/v1/media', { headers: bearer(strangerBody.access_token) })).status(),
    ).toBe(200)
  })

  test('upload limits reject oversized files, unsupported formats and unknown kinds', async ({
    request,
  }) => {
    const member = await registerMember(request, 'upload-limits', { onboard: false })

    const oversized = await request.post('/api/v1/media/upload', {
      headers: bearer(member.accessToken),
      multipart: {
        file: { name: 'huge.png', mimeType: 'image/png', buffer: Buffer.alloc(9 * 1024 * 1024) },
        kind: 'photo',
      },
    })
    expect(oversized.status()).toBe(422)
    expect(await oversized.text()).toMatch(/file_too_large|exceeds/i)

    const wrongType = await request.post('/api/v1/media/upload', {
      headers: bearer(member.accessToken),
      multipart: {
        file: { name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('not an image') },
        kind: 'photo',
      },
    })
    expect(wrongType.status()).toBe(422)
    expect(await wrongType.text()).toMatch(/unsupported_media|Unsupported/i)

    const badKind = await request.post('/api/v1/media/upload', {
      headers: bearer(member.accessToken),
      multipart: {
        file: { name: 'portrait.png', mimeType: 'image/png', buffer: PORTRAIT },
        kind: 'export',
      },
    })
    expect(badKind.status()).toBe(422)
    expect(await badKind.text()).toMatch(/bad_kind|generated by the server/i)
  })

  test('input validation and role enforcement happen on the server', async ({ request }) => {
    const invalidRegistration = await request.post('/api/v1/auth/register', {
      data: {
        email: 'not-an-email',
        password: 'short',
        full_name: 'X',
        accept_terms: false,
      },
    })
    expect(invalidRegistration.status()).toBe(422)

    expect((await request.get('/api/v1/profile')).status()).toBe(401)
    expect((await request.get('/api/v1/admin/stats')).status()).toBe(401)

    const member = await registerMember(request, 'role-check', { onboard: false })
    expect(
      (await request.get('/api/v1/admin/stats', { headers: bearer(member.accessToken) })).status(),
    ).toBe(403)
    expect(
      (await request.get('/api/v1/admin/users', { headers: bearer(member.accessToken) })).status(),
    ).toBe(403)
  })

  test('no AI provider is configured, so the stylist reports rule-based mode', async ({ request }) => {
    const member = await registerMember(request, 'ai-check')
    const capabilities = await request.get('/api/v1/ai/capabilities', {
      headers: bearer(member.accessToken),
    })
    expect(capabilities.ok()).toBeTruthy()
    const body = (await capabilities.json()) as { assistant_mode: string; providers: { usable: boolean }[] }
    expect(body.assistant_mode).toBe('rule_based')
    expect(body.providers.every((provider) => !provider.usable)).toBe(true)

    const assistant = await request.post('/api/v1/ai/assistant', {
      headers: bearer(member.accessToken),
      data: { message: 'What should I wear to a summer wedding?', history: [] },
    })
    expect(assistant.ok()).toBeTruthy()
    const reply = (await assistant.json()) as {
      mode: string
      provider: string
      text: string
      disclaimer: string | null
      looks: unknown[]
    }
    expect(reply.mode).toBe('rule_based')
    expect(reply.provider).toBe('local')
    expect(reply.text.length).toBeGreaterThan(30)
    expect(reply.disclaimer).toBeTruthy()
    expect(reply.looks.length).toBeGreaterThanOrEqual(0)

    const tryOn = await request.get('/api/v1/try-on/capabilities', {
      headers: bearer(member.accessToken),
    })
    expect(tryOn.ok()).toBeTruthy()
    const tryOnBody = (await tryOn.json()) as { ready?: boolean; available?: boolean; reason?: string }
    expect(tryOnBody.ready ?? tryOnBody.available).toBe(false)
  })
})
