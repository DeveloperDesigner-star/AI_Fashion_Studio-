def slugify(value: str) -> str:
    """ASCII slug that keeps accented product words readable in a URL."""
    decomposed = unicodedata.normalize("NFKD", value)
    ascii_only = decomposed.encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", ascii_only.lower()).strip("-")


def build_catalog_garments() -> list[dict[str, Any]]:
    """Expand the template/variant matrix into seeder rows."""
    garments: list[dict[str, Any]] = []
    for template in TEMPLATES:
        size_key = template.get("sizes", "apparel")
        for name, palette_key, price_delta, extra_styles, extra_occasions, featured in template["variants"]:
            primary, secondary, accent = PALETTES[palette_key]
            styles = list(dict.fromkeys([*template["styles"], *extra_styles]))
            occasions = list(dict.fromkeys([*template["occasions"], *extra_occasions]))
            slug = f"{template['key']}-{slugify(name)}"
            garments.append(
                {
                    "slug": slug,
                    "name": f"{name} {template['name']}",
                    "gender": template["gender"],
                    "category": template["category"],
                    "slot": template["slot"],
                    "description": template["description"],
                    "story": template["story"],
                    "base_price_cents": template["price"] + price_delta,
                    "default_fabric": template["fabric"],
                    "default_color": primary,
                    "season": template["season"],
                    "styles": styles,
                    "occasions": occasions,
                    "sizes": SIZE_SETS[size_key],
                    "fit": template["fit"],
                    "tags": list(dict.fromkeys([*occasions, *styles, template["category"]])),
                    "silhouette": template["silhouette"],
                    "palette": {"primary": primary, "secondary": secondary, "accent": accent},
                    "is_featured": featured,
                    "components": template["components"],
                }
            )
    return garments


