"""Private media uploads, photo analysis and print preparation."""

from __future__ import annotations

import uuid
from pathlib import Path

from fastapi import APIRouter, File, Form, HTTPException, Query, Request, Response, UploadFile, status
from fastapi.responses import FileResponse
from sqlalchemy import func, select

from app.api.v1.deps import CurrentUser, DbSession
from app.core.config import settings
from app.core.rate_limit import client_identity, enforce
from app.models.enums import MediaKind, PhotoView
from app.models.media import MediaAsset
from app.schemas.media import (
    MediaListResponse,
    MediaRead,
    PaletteResponse,
    PhotoAnalysisResponse,
    PrintSheetRequest,
    PrintSheetResponse,
)
from app.services import audit, imaging, storage

router = APIRouter(prefix="/media", tags=["media"])

ALLOWED_KINDS = {kind.value for kind in MediaKind}


def _media_url(asset_id: uuid.UUID) -> str:
    return f"{settings.api_v1_prefix}/media/{asset_id}/content"


def _to_read(asset: MediaAsset) -> MediaRead:
    data = MediaRead.model_validate(asset)
    data.url = _media_url(asset.id)
    data.thumbnail_url = (
        f"{settings.api_v1_prefix}/media/{asset.id}/content?thumbnail=true"
        if asset.thumbnail_key
        else None
    )
    return data


def _owned_asset(db, user, asset_id: uuid.UUID) -> MediaAsset:
    asset = db.scalar(
        select(MediaAsset).where(MediaAsset.id == asset_id, MediaAsset.user_id == user.id)
    )
    if asset is None:
        raise HTTPException(status_code=404, detail={"code": "not_found", "message": "File not found."})
    return asset


@router.post("/upload", response_model=MediaRead, status_code=status.HTTP_201_CREATED)
async def upload_media(
    request: Request,
    user: CurrentUser,
    db: DbSession,
    file: UploadFile = File(...),
    kind: str = Form(default="photo"),
    view: str | None = Form(default=None),
) -> MediaRead:
    enforce("upload", client_identity(request), settings.upload_rate_limit_per_minute)

    if kind not in ALLOWED_KINDS:
        raise HTTPException(status_code=422, detail={"code": "bad_kind", "message": "Unknown media kind."})
    if kind == MediaKind.EXPORT:
        raise HTTPException(
            status_code=422,
            detail={"code": "bad_kind", "message": "Exports are generated by the server."},
        )

    photo_view: str | None = None
    min_edge: int | None = None
    min_portrait_ratio: float | None = None
    if view:
        allowed_views = {member.value for member in PhotoView}
        if view not in allowed_views:
            raise HTTPException(
                status_code=422,
                detail={"code": "bad_view", "message": "Unknown photo view."},
            )
        if kind != MediaKind.PHOTO:
            raise HTTPException(
                status_code=422,
                detail={
                    "code": "bad_view",
                    "message": "Photo views only apply to reference photos.",
                },
            )
        photo_view = view
        if view in {PhotoView.FRONT, PhotoView.SIDE, PhotoView.BACK, PhotoView.FULL_BODY}:
            min_edge = 480
        if view == PhotoView.FULL_BODY:
            min_portrait_ratio = 1.15
        elif view == PhotoView.PROFILE:
            min_edge = 200

    count = db.scalar(select(func.count(MediaAsset.id)).where(MediaAsset.user_id == user.id)) or 0
    if count >= settings.max_uploads_per_user:
        raise HTTPException(
            status_code=400,
            detail={
                "code": "upload_limit",
                "message": f"Upload limit reached ({settings.max_uploads_per_user} files). Delete some files first.",
            },
        )

    data = await file.read(settings.max_upload_bytes + 1)
    try:
        stored = storage.save_image(
            data=data,
            original_filename=file.filename or "upload.jpg",
            kind=kind,
            make_thumbnail=kind != MediaKind.PRINT,
            min_edge=min_edge,
            min_portrait_ratio=min_portrait_ratio,
        )
    except storage.UploadError as exc:
        raise HTTPException(
            status_code=422, detail={"code": exc.code, "message": exc.message}
        ) from exc

    asset = MediaAsset(
        user_id=user.id,
        kind=kind,
        photo_view=photo_view,
        original_filename=storage.sanitize_filename(file.filename or "upload.jpg"),
        storage_key=stored.storage_key,
        thumbnail_key=stored.thumbnail_key,
        mime_type=stored.mime_type,
        byte_size=stored.byte_size,
        width=stored.width,
        height=stored.height,
        checksum_sha256=stored.checksum_sha256,
        is_private=True,
    )
    db.add(asset)
    db.flush()
    audit.record(db, action="media.uploaded", user=user, request=request, resource_type="media",
                 resource_id=asset.id,
                 detail={"kind": kind, "view": photo_view, "bytes": stored.byte_size})
    return _to_read(asset)


@router.get("", response_model=MediaListResponse)
def list_media(user: CurrentUser, db: DbSession, kind: str | None = None) -> MediaListResponse:
    stmt = select(MediaAsset).where(MediaAsset.user_id == user.id)
    if kind:
        stmt = stmt.where(MediaAsset.kind == kind)
    assets = db.scalars(stmt.order_by(MediaAsset.created_at.desc())).all()
    used = sum(asset.byte_size for asset in assets)
    return MediaListResponse(
        items=[_to_read(asset) for asset in assets],
        total=len(assets),
        storage_used_bytes=used,
        storage_limit_bytes=settings.max_uploads_per_user * settings.max_upload_bytes,
    )


@router.get("/{asset_id}/content")
def get_media_content(
    asset_id: uuid.UUID,
    user: CurrentUser,
    db: DbSession,
    thumbnail: bool = Query(default=False),
) -> FileResponse:
    asset = _owned_asset(db, user, asset_id)
    key = asset.thumbnail_key if thumbnail and asset.thumbnail_key else asset.storage_key
    path = storage.path_for(key)
    if not path.exists():
        raise HTTPException(status_code=410, detail={"code": "file_missing", "message": "The stored file is missing."})
    headers = {"Cache-Control": "private, max-age=300"}
    if asset.kind == MediaKind.EXPORT:
        headers["Content-Disposition"] = f'attachment; filename="{asset.original_filename}"'
    return FileResponse(path, media_type=asset.mime_type if not thumbnail else "image/webp", headers=headers)


@router.delete("/{asset_id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_media(asset_id: uuid.UUID, user: CurrentUser, db: DbSession) -> Response:
    asset = _owned_asset(db, user, asset_id)
    storage.delete_file(asset.storage_key)
    storage.delete_file(asset.thumbnail_key)
    db.delete(asset)
    db.flush()
    audit.record(db, action="media.deleted", user=user, resource_type="media", resource_id=asset_id)
    return Response(status_code=status.HTTP_204_NO_CONTENT)


@router.post("/{asset_id}/analyze", response_model=PhotoAnalysisResponse)
def analyze_media(asset_id: uuid.UUID, user: CurrentUser, db: DbSession) -> PhotoAnalysisResponse:
    asset = _owned_asset(db, user, asset_id)
    try:
        metrics = imaging.analyze_photo(storage.path_for(asset.storage_key))
    except imaging.ImagingError as exc:
        raise HTTPException(status_code=422, detail={"code": "analysis_failed", "message": exc.message}) from exc
    return PhotoAnalysisResponse(asset_id=asset.id, metrics=metrics)


@router.get("/{asset_id}/palette", response_model=PaletteResponse)
def palette(asset_id: uuid.UUID, user: CurrentUser, db: DbSession, colors: int = Query(default=5, ge=2, le=8)) -> PaletteResponse:
    asset = _owned_asset(db, user, asset_id)
    try:
        result = imaging.extract_palette(storage.path_for(asset.storage_key), colors=colors)
    except imaging.ImagingError as exc:
        raise HTTPException(status_code=422, detail={"code": "palette_failed", "message": exc.message}) from exc
    return PaletteResponse(asset_id=asset.id, palette=result)


@router.post("/{asset_id}/print-sheet", response_model=PrintSheetResponse, status_code=status.HTTP_201_CREATED)
def create_print_sheet(
    asset_id: uuid.UUID, payload: PrintSheetRequest, user: CurrentUser, db: DbSession, request: Request
) -> PrintSheetResponse:
    asset = _owned_asset(db, user, asset_id)
    if asset.kind not in {MediaKind.PRINT, MediaKind.CLOTHING, MediaKind.REFERENCE}:
        raise HTTPException(
            status_code=422,
            detail={
                "code": "wrong_kind",
                "message": "Print sheets can be built from print, reference or clothing artwork.",
            },
        )
    source = storage.path_for(asset.storage_key)
    try:
        sheet_bytes, meta = imaging.build_print_sheet(
            source.read_bytes(),
            width_cm=payload.width_cm,
            height_cm=payload.height_cm,
            dpi=payload.dpi,
            fabric=payload.fabric,
            title=payload.title,
        )
    except (imaging.ImagingError, OSError) as exc:
        raise HTTPException(
            status_code=422,
            detail={"code": "print_failed", "message": getattr(exc, "message", "Could not build the print sheet.")},
        ) from exc

    stored = storage.save_image(
        data=sheet_bytes,
        original_filename=f"print-sheet-{asset_id.hex[:8]}.png",
        kind=MediaKind.EXPORT.value,
        make_thumbnail=True,
    )
    export = MediaAsset(
        user_id=user.id,
        kind=MediaKind.EXPORT.value,
        original_filename=f"print-sheet-{asset_id.hex[:8]}.png",
        storage_key=stored.storage_key,
        thumbnail_key=stored.thumbnail_key,
        mime_type=stored.mime_type,
        byte_size=stored.byte_size,
        width=stored.width,
        height=stored.height,
        checksum_sha256=stored.checksum_sha256,
        is_private=True,
    )
    db.add(export)
    db.flush()
    audit.record(db, action="media.print_sheet", user=user, request=request, resource_type="media",
                 resource_id=export.id, detail=meta)
    return PrintSheetResponse(
        filename=export.original_filename,
        content_type="image/png",
        meta=meta,
        download_url=_media_url(export.id),
    )


@router.get("/{asset_id}/download")
def download_asset(asset_id: uuid.UUID, user: CurrentUser, db: DbSession) -> FileResponse:
    asset = _owned_asset(db, user, asset_id)
    path: Path = storage.path_for(asset.storage_key)
    if not path.exists():
        raise HTTPException(status_code=410, detail={"code": "file_missing", "message": "The stored file is missing."})
    return FileResponse(
        path,
        media_type=asset.mime_type,
        filename=asset.original_filename,
        headers={"Cache-Control": "private, no-store"},
    )
