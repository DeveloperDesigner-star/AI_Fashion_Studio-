def safe_model_metadata() -> dict[str, str]:
    """Model attribution saved with each result (never worker credentials)."""

    return {
        "name": settings.tryon_model_name or MODEL_NAME,
        "license": MODEL_LICENSE,
        "license_url": settings.tryon_license_url or MODEL_LICENSE_URL,
        "repository": settings.tryon_model_repo or MODEL_REPO,
        "attribution": MODEL_ATTRIBUTION,
    }


def cloth_type_for_slot(slot: str) -> str | None:
    """Map catalogue slots to CatVTON's three supported garment regions.

    Components (sleeves, collars, cuffs) travel with their parent garment, so a
    kameez/shirt/waistcoat/jacket is an ``upper`` garment, a shalwar/trouser is
    ``lower``, and a full-length kameez/shalwar suit or dress is ``overall``.
    """

    if slot in {"top", "outerwear"}:
        return "upper"
    if slot == "bottom":
        return "lower"
    if slot == "dress":
        return "overall"
    return None


def unavailable_availability(reason: str, checks: list[TryOnCheck] | None = None) -> TryOnAvailability:
    return TryOnAvailability(
        available=False,
        status="unavailable",
        provider="catvton-self-hosted",
        reason=reason,
        checks=checks or [],
    )
