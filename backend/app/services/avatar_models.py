DEFAULT_BASE_MODEL = "willow"

#: Allowed range for each manual slider. 1.0 means "as measured".
ADJUSTMENT_BOUNDS: dict[str, tuple[float, float]] = {
    "height": (0.94, 1.06),
    "build": (0.90, 1.10),
    "shoulder": (0.90, 1.10),
    "torso": (0.95, 1.05),
    "leg": (0.95, 1.05),
}

DEFAULT_ADJUSTMENTS: dict[str, float] = dict.fromkeys(ADJUSTMENT_BOUNDS, 1.0)


def list_base_models() -> list[dict[str, Any]]:
    return list(BASE_MODELS.values())


def get_base_model(slug: str) -> dict[str, Any] | None:
    return BASE_MODELS.get(slug)


def normalize_adjustments(values: dict[str, Any] | None) -> dict[str, float]:
    """Clamp submitted sliders to the supported range.

    Unknown keys are dropped and non-numeric values fall back to 1.0 so a bad
    payload can never distort the renderer.
    """
    normalized = dict(DEFAULT_ADJUSTMENTS)
    for key, (low, high) in ADJUSTMENT_BOUNDS.items():
        raw = (values or {}).get(key)
        try:
            number = float(raw)  # type: ignore[arg-type]
        except (TypeError, ValueError):
            continue
        normalized[key] = round(max(low, min(high, number)), 3)
    return normalized


def apply_adjustments(parameters: dict[str, Any], adjustments: dict[str, Any] | None) -> dict[str, Any]:
    """Return a copy of the measurement-derived parameters with sliders applied."""
    adjusted = dict(parameters or {})
    sliders = normalize_adjustments(adjustments)

    def scale(key: str, factor: float) -> None:
        value = adjusted.get(key)
        if isinstance(value, (int, float)):
            adjusted[key] = round(float(value) * factor, 3)

    scale("height_m", sliders["height"])
    scale("head_height", sliders["height"])
    scale("shoulder_width", sliders["shoulder"] * sliders["build"])
    scale("chest_width", sliders["build"])
    scale("chest_depth", sliders["build"])
    scale("waist_width", sliders["build"])
    scale("waist_depth", sliders["build"])
    scale("hip_width", sliders["build"])
    scale("hip_depth", sliders["build"])
    scale("thigh_width", sliders["build"])
    scale("calf_width", sliders["build"])
    scale("torso_length", sliders["torso"])
    scale("leg_length", sliders["leg"])
    scale("arm_length", sliders["leg"] * 0.5 + sliders["height"] * 0.5)

    adjusted["adjustments"] = sliders
    return adjusted
